def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def mean_ci(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return None, None
    m = sum(xs) / len(xs)
    if len(xs) < 2:
        return m, 0.0
    t = {2: 12.71, 3: 4.30, 4: 3.18, 5: 2.78, 6: 2.57, 7: 2.45, 8: 2.36, 9: 2.31, 10: 2.26}.get(len(xs), 2.0)
    return m, t * st.stdev(xs) / math.sqrt(len(xs))


def mann_whitney(a, b):
    na, nb = len(a), len(b)
    if not na or not nb:
        return None, None
    allv = sorted([(v, 0) for v in a] + [(v, 1) for v in b])
    ranks, i = [0.0] * len(allv), 0
    while i < len(allv):
        j = i
        while j + 1 < len(allv) and allv[j + 1][0] == allv[i][0]:
            j += 1
        for k in range(i, j + 1):
            ranks[k] = (i + j) / 2 + 1
        i = j + 1
    ra = sum(r for r, (_, g) in zip(ranks, allv) if g == 0)
    u = ra - na * (na + 1) / 2
    n = na + nb
    ties = defaultdict(int)
    for v, _ in allv:
        ties[v] += 1
    s2 = na * nb / 12 * ((n + 1) - sum(t ** 3 - t for t in ties.values()) / (n * (n - 1)))
    if s2 <= 0:
        return u, 1.0
    z = (u - na * nb / 2) / math.sqrt(s2)
    return u, math.erfc(abs(z) / math.sqrt(2))


def at_programs(series, n, key="pct"):
    last = 0.0
    for s in series:
        if s["n_programs"] > n:
            break
        last = s[key] if key in s else last
    return last


def tex_escape(s: str) -> str:
    return s.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


_DIGITS = dict(zip("0123456789", ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")))


def macro_name(s: str) -> str:
    """TeX-safe CamelCase name: digits spelled out, separators dropped, interior capitals kept (L1 -> LOne)."""
    s = "".join(_DIGITS.get(c, c) for c in s)
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z]+", s) if p)


class Macros:
    def __init__(self):
        self.items: dict[str, str] = {}

    def __setitem__(self, k, v):
        self.items[macro_name(k)] = str(v)

    def tex(self) -> str:
        return "% generated by tools/compare_literature.py -- do not edit\n" + "\n".join(
            f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.items.items()))


def fmt(x, d=1):
    return "--" if x is None else (f"{x:,.{d}f}" if isinstance(x, float) else f"{x:,}")


