    if not d:
        return ""
    res = d["results"]
    det = [r for r in res.values() if r.get("detected")]
    M["EOneBugs"], M["EOneDetected"] = len(res), len(det)
    M["EOneLocHit"] = sum(bool(r.get("localization_contains_fault")) for r in det)
    M["EOnePrimaryHit"] = sum(bool(r.get("primary_contains_fault")) for r in det)
    lines = ["\\begin{tabular}{@{}l c l r r c c@{}}\\toprule",
             "Bug & Tier & Failing field / kind & Stim. & Min. & Loc. & Hit\\\\\\midrule"]
    for bid, r in res.items():
        if r.get("detected"):
            hit = "\\checkmark" if r["localization_contains_fault"] else "$\\times$"
            lines.append(f"\\texttt{{{tex_escape(bid)}}} & {r['level']} & {tex_escape(r.get('failure_kind') or '')} & {r['original_length']} & "
                         f"{r['minimal_length']} & {tex_escape(r['localized_subsystem'])} & {hit}\\\\")
        else:
            lines.append(f"\\texttt{{{tex_escape(bid)}}} & -- & \\multicolumn{{5}}{{l}}{{not observable ({tex_escape(r.get('error') or 'equivalent mutant')})}}\\\\")
    md.append(f"## E1 bug suite\n- {len(det)}/{len(res)} bugs detected by their targeted stimulus; localisation contains the fault for "
              f"{M.items['EOneLocHit']}/{len(det)} (primary block {M.items['EOnePrimaryHit']}/{len(det)})")
