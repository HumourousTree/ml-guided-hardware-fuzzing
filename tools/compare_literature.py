def section_repair(logs, M, md):
    d = load(logs / "experiments" / "repair_baselines.json")
    if not d:
        return ""
    by = defaultdict(dict)
    for k, r in d.items():
        b, m = k.split("|")
        by[b][m] = r
    det = {b: v for b, v in by.items() if any(x.get("detected") for x in v.values())}
    M["RepBugs"] = len(det)
    cnt = lambda m, f: sum(1 for v in det.values() if m in v and f(v[m]))
    M["RepOracleAccepted"] = cnt("oracle", lambda r: r.get("accepted"))
    M["RepOracleCorrect"] = cnt("oracle", lambda r: r.get("correct_on_held_out"))
    M["RepLintRecovered"] = cnt("lint-oracle", lambda r: r.get("accepted") and r.get("llm_calls") == 2)
    M["RepNoopRejected"] = cnt("noop", lambda r: r.get("detected") and not r.get("accepted"))
    M["RepTplAccepted"] = cnt("template", lambda r: r.get("accepted"))
    M["RepTplCorrect"] = cnt("template", lambda r: r.get("correct_on_held_out"))
    M["RepTplExact"] = cnt("template", lambda r: r.get("exact_fix"))
    M["RepTplOverfit"] = cnt("template", lambda r: r.get("accepted") and not r.get("correct_on_held_out"))
    rej = defaultdict(int)
    for v in det.values():
        for k, n in (v.get("template", {}).get("rejections") or {}).items():
            rej[k] += n
    for k, n in rej.items():
        M[f"RepRej{macro_name(k)}"] = n
    tried = [v["template"]["candidates_tried"] for v in det.values() if v.get("template", {}).get("accepted")]
    M["RepTplTriedMedian"] = f"{st.median(tried):.0f}" if tried else "--"
    lines = ["\\begin{tabular}{@{}l c c c c r c c@{}}\\toprule",
             "& \\multicolumn{3}{c}{Guard controls} & \\multicolumn{4}{c}{SBFL template repair (budget 60)}\\\\\\cmidrule(lr){2-4}\\cmidrule(l){5-8}",
             "Bug & Oracle & Lint$\\rightarrow$retry & No-op & Acc. & Tried & Held-out & Exact\\\\\\midrule"]
    ck = lambda x: "\\checkmark" if x else "$\\times$"
    for b, v in sorted(det.items(), key=lambda kv: kv[0]):
        o, l, n, t = v.get("oracle", {}), v.get("lint-oracle", {}), v.get("noop", {}), v.get("template", {})
        lines.append(f"\\texttt{{{tex_escape(b)}}} & {ck(o.get('accepted'))} & {ck(l.get('accepted') and l.get('llm_calls') == 2)} & "
                     f"{'rej.' if n and not n.get('accepted') else 'ACC'} & {ck(t.get('accepted'))} & {t.get('candidates_tried', '--')} & "
                     f"{(str(t.get('held_out_pass')) + '/' + str(t.get('held_out_total'))) if t.get('accepted') else '--'} & "
                     f"{ck(t.get('exact_fix')) if t.get('accepted') else '--'}\\\\")
    md.append(f"## Guarded repair (no LLM key available: controls + template baseline)\n- oracle accepted {M.items['RepOracleAccepted']}/{len(det)}, "
              f"lint-broken patch recovered on retry {M.items['RepLintRecovered']}/{len(det)}, no-op rejected {M.items['RepNoopRejected']}/{len(det)}\n"
              f"- template repair: accepted {M.items['RepTplAccepted']}/{len(det)}, correct on held-out {M.items['RepTplCorrect']}, exact {M.items['RepTplExact']}, "
              f"overfitting accepted {M.items['RepTplOverfit']}; rejections by gate: {dict(rej)}")
    return "\n".join(lines + ["\\bottomrule\\end{tabular}"])


def section_unified(logs, M, md, figs, plt):
    d = load(logs / "experiments" / "unified_coverage.json")
    if not d:
        return ""
    by = defaultdict(list)
    for r in d["runs"]:
        by[r["method"]].append(r)
    M["UniIssStatements"] = d["iss_statements"]
    w = d["weights"]
    M["UniWeights"] = ", ".join(f"{v:g}" for v in w.values())
    lines = ["\\begin{tabular}{@{}l r r r r r@{}}\\toprule",
             "Method & $C_{\\mathrm{line}}$ & $C_{\\mathrm{tog}}$ & $C_{\\mathrm{ISS}}$ & $C_{\\mathrm{func}}$ & $C_U$\\\\\\midrule"]
    for m in ("random", "mutation", "hybrid-rand"):
        rs = by.get(m)
        if not rs:
            continue
        vals = {k: mean_ci([r["final"][k] for r in rs]) for k in ("C_line", "C_toggle", "C_ISS", "C_func", "C_U")}
        lines.append(f"{METHOD_LABEL[m]} & " + " & ".join(f"{vals[k][0]:.2f}" for k in ("C_line", "C_toggle", "C_ISS", "C_func", "C_U")) + "\\\\")
        for k, v in vals.items():
            M[f"Uni{macro_name(m)}{macro_name(k)}"] = f"{v[0]:.2f}"
    # instruction skew (pooled over every program of every method)
    mix = defaultdict(float)
    for r in d["runs"]:
        for k, v in r["mnemonic_mix_pct"].items():
            mix[k] += v / len(d["runs"])
    cats = {"ALU-imm": {"addi", "slti", "sltiu", "xori", "ori", "andi", "slli", "srli", "srai"},
            "ALU-reg": {"add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and"},
            "MUL/DIV": {"mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu"},
            "Branch": {"beq", "bne", "blt", "bge", "bltu", "bgeu"}, "Jump": {"jal", "jalr"},
            "Load": {"lb", "lh", "lw", "lbu", "lhu"}, "Store": {"sb", "sh", "sw"}, "LUI/AUIPC": {"lui", "auipc"}}
    catmix = {c: sum(mix.get(x, 0) for x in s) for c, s in cats.items()}
    for c, v in catmix.items():
        M[f"MixBench{macro_name(c)}"] = f"{v:.1f}"
    missing = defaultdict(int)
    for r in d["runs"]:
        for g, bins in r["functional"]["missing"].items():
            for b in bins:
                missing[(g, b)] += 1
    always = sorted(b for (g, b), n in missing.items() if n == len(d["runs"]))
    M["UniAlwaysMissing"] = tex_escape(", ".join(always)) or "none"
    md.append("## Unified coverage\n" + "\n".join(f"- {r['method']} seed {r['seed']}: {r['final']}" for r in d["runs"][:12])
              + f"\n- bins never hit by any run: {', '.join(always) or 'none'}\n- benchmark instruction mix (%): {json.dumps({k: round(v, 1) for k, v in catmix.items()})}")
    if plt and by:
        fig, axs = plt.subplots(1, 4, figsize=(7.0, 1.9), sharex=True)
        for ax, k in zip(axs, ("C_line", "C_toggle", "C_ISS", "C_func")):
            for m, rs in by.items():
                xs = [p["n_programs"] for p in rs[0]["trajectory"]]
                ys = [st.mean(r["trajectory"][i][k] for r in rs if i < len(r["trajectory"])) for i in range(len(xs))]
                ax.plot(xs, ys, color=COLORS.get(m), lw=1.1, label=METHOD_PLAIN.get(m, m), marker="o", ms=1.8)
            ax.set_xscale("log"); ax.set_title(k.replace("C_", "C ").replace("ISS", "ISS stmt").replace("func", "functional"), fontsize=7)
            ax.grid(alpha=.3, lw=.4); ax.tick_params(labelsize=6)
        axs[0].set_ylabel("%", fontsize=7); axs[0].legend(fontsize=5.5)
        fig.text(0.5, 0.01, "validated programs (log)", ha="center", fontsize=7); fig.tight_layout(rect=(0, .05, 1, 1))
        fig.savefig(figs / "fig_unified_components.pdf"); plt.close(fig)
    return "\n".join(lines + ["\\bottomrule\\end{tabular}"])


